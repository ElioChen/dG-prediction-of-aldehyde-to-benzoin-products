#!/usr/bin/env python3
"""Rec-2 prep: inventory homo_v6 library files, id-normalise, cross-check coverage.
Writes homo_v6/LIBRARY_MANIFEST.md. Reads only id columns -> login-node safe."""
import pandas as pd, numpy as np, pathlib, sys, io

H = pathlib.Path("/gpfs/scratch1/shared/schen3/benzoin-dg-restored/data/cross_benzoin/homo_v6")

def norm_id(s):
    """Canonicalise ids that recovery wrote as '2.0' floats back to '2' strings."""
    x = pd.to_numeric(s, errors="coerce")
    out = pd.Series(pd.NA, index=s.index, dtype="object")
    ok = x.notna()
    out[ok] = x[ok].round().astype("int64").astype(str)
    # non-numeric ids: keep original stripped
    out[~ok] = s[~ok].astype(str).str.strip()
    return out

def load_ids(fname, col):
    p = H / fname
    df = pd.read_csv(p, usecols=[col], dtype=str)
    raw = df[col]
    nid = norm_id(raw)
    return raw, nid

specs = [
    # (file, id_col, side)
    ("aldehydes_all.csv", "id", "ald"),
    ("aldehydes_mordred_slim102.csv", "id", "ald"),
    ("aldehydes_bde_alfabet.csv", "id", "ald"),
    ("aldehydes_bdfe_gxtb_descriptors.csv", "id", "ald"),
    ("aldehydes_scaffold_split_from_dG.csv", "id", "ald"),
    ("products_all.csv", "id", "prod"),
    ("products_bde_alfabet.csv", "id", "prod"),
    ("products_bdfe_gxtb_descriptors.csv", "id", "prod"),
    ("products_scaffold_split.csv", "id", "prod"),
]

info = {}
for fname, col, side in specs:
    raw, nid = load_ids(fname, col)
    looks_float = bool(raw.astype(str).str.match(r"^-?\d+\.0+$").any())
    ndup = int(nid.duplicated().sum())
    info[fname] = dict(side=side, n=len(nid), col=col, looks_float=looks_float,
                       ndup=ndup, ids=set(nid.dropna()), sample=list(raw.head(3)))

ald_ref = info["aldehydes_all.csv"]["ids"]
prod_ref = info["products_all.csv"]["ids"]

out = io.StringIO()
w = out.write
w("# homo_v6 LIBRARY MANIFEST\n\n")
w("Generated by `scratchpad/rec2_library_manifest.py` (Rec-2 prep, 2026-09-08).\n")
w("Reference id sets: `aldehydes_all.csv` (%d ald ids), `products_all.csv` (%d prod ids).\n\n" % (len(ald_ref), len(prod_ref)))
w("**id-normalisation required**: several recovered CSVs store ids as `'2.0'` floats. "
  "String-merging those to the `'2'`-id canonical tables silently joins ~0 rows. "
  "Assembler MUST pass every id column through `pipeline/bde/qc.py::norm_id` (commit 826c0e9) — see memory `bde-recovered-csv-float-id`.\n\n")
w("After `norm_id`, aldehyde-side coverage is ~209.3k/209.5k (99.9%) and product-side ~182-183k/184.2k (~99%); "
  "the sub-1%% gaps are errored/updated species and are handled by median-impute in the assembler, same as `predict_dg.py` does for new pairs.\n\n")
w("| file | side | rows | id col | float-id? | dup ids (norm) | in ref | ref-only (missing) |\n")
w("|---|---|--:|---|:-:|--:|--:|--:|\n")
for fname, col, side in specs:
    d = info[fname]
    ref = ald_ref if side == "ald" else prod_ref
    inref = len(d["ids"] & ref)
    refonly = len(ref - d["ids"])
    w("| `%s` | %s | %d | %s | %s | %d | %d | %d |\n" % (
        fname, side, d["n"], col, "YES" if d["looks_float"] else "no",
        d["ndup"], inref, refonly))
w("\n## id sample (first 3 raw values)\n\n")
for fname, col, side in specs:
    w("- `%s`: %s\n" % (fname, info[fname]["sample"]))

# homo_pairs coverage vs aldehyde ref (donor==acceptor for homo)
hp = pd.read_csv(H / "homo_pairs.csv", usecols=["donor_id", "acceptor_id"], dtype=str)
hp_d = norm_id(hp["donor_id"]); hp_a = norm_id(hp["acceptor_id"])
n_homo = int((hp_d == hp_a).sum())
donor_in_ald = len(set(hp_d.dropna()) & ald_ref)
w("\n## homo_pairs.csv\n\n")
w("- rows: %d ; donor==acceptor: %d\n" % (len(hp), n_homo))
w("- distinct donor ids: %d ; of those in `aldehydes_all.csv`: %d\n" % (len(set(hp_d.dropna())), donor_in_ald))

# 30k labelled subset
lab = pd.read_csv("/gpfs/scratch1/shared/schen3/benzoin-dg-restored/data/cross_benzoin/homo_unify/homo_unify_v1_dft.csv", dtype=str)
w("\n## homo_unify_v1_dft.csv (surviving DFT labels)\n\n")
w("- rows: %d ; columns: %s\n" % (len(lab), list(lab.columns)))
lid = norm_id(lab[lab.columns[0]])
w("- label ids in product ref: %d ; in aldehyde ref: %d\n" % (
    len(set(lid.dropna()) & prod_ref), len(set(lid.dropna()) & ald_ref)))

txt = out.getvalue()
(H / "LIBRARY_MANIFEST.md").write_text(txt)
print(txt)
